// The avatar pictures a person can choose from: six families of twenty.
//
// A picture is plain data: a list of shapes for a 40 by 40 box, each with one
// class that the wearer's tone-* class colours (index.css, .avatar-art). It is
// drawn by AvatarArt.tsx with React.createElement, never as markup: the id of
// the picture to draw comes from a value another client stored.
//
// This file was first written by a script from the designer's SVG files and is
// now the source. To add or change a picture, edit its shapes here, with the
// closed vocabulary __tests__/avatarArt.test.tsx checks (tags, classes,
// attributes). A new picture also needs its id in utils/avatars.js (the list
// the server accepts: a new id ships in two releases, see AGENTS.md) and its
// name in i18n/locales/{en,fr}/avatars.ts.

import type { MessageKey } from '../../../i18n/messages';

export type AvatarShapeClass = 'bg' | 'pop' | 'light' | 'ink' | 'dot' | 'shade' | 'blush';
export type AvatarShapeTag = 'path' | 'circle' | 'ellipse' | 'rect' | 'line' | 'polygon' | 'polyline' | 'g';

export interface AvatarShape {
  readonly tag: AvatarShapeTag;
  /** Absent on a group only. */
  readonly class?: AvatarShapeClass;
  readonly d?: string;
  readonly cx?: number;
  readonly cy?: number;
  readonly r?: number;
  readonly rx?: number;
  readonly ry?: number;
  readonly x?: number;
  readonly y?: number;
  readonly width?: number;
  readonly height?: number;
  readonly x1?: number;
  readonly y1?: number;
  readonly x2?: number;
  readonly y2?: number;
  readonly points?: string;
  readonly transform?: string;
  /** A group's shapes. */
  readonly children?: readonly AvatarShape[];
}

